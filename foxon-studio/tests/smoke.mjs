import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const root="foxon-studio/";
const read=name=>readFileSync(root+name,"utf8");
const shell=read("shell.js"),calendar=read("app.js");
const upgrade=read("studio-upgrades.js"),css=read("studio-upgrades.css");
const index=read("index.html"),boot=read("bootstrap.js");
const themeKeys=["classic","graphite","midnight","forest","copper","paper","slate","ocean","sand","futuristic","steampunk","christmas","synthwave","arcade"];
for(const theme of themeKeys)assert(shell.includes('<option value="'+theme+'">'),"Missing selectable theme: "+theme);
assert.equal((shell.match(/class="stat-mark-symbol"/g)||[]).length,4,"Four stat icons must be explicit SVGs");
assert(calendar.includes('data-date="'),"Calendar days need canonical drop dates");
assert(calendar.includes("foxon:post-saved"),"Successful post saves must trigger an upgrade refresh");
assert(upgrade.includes('["idea","draft"]'),"Only editable draft stages may be dragged");
assert(upgrade.includes('.eq("id",id).in("status",["idea","draft"]).select("id").maybeSingle()'),"Calendar updates must verify the affected row");
assert(upgrade.includes('db.from("studio_brain_entries")'),"Builder should use verified FOXON Brain sources");
assert(upgrade.includes('.eq("verification","approved")'),"Brain suggestions must be approved");
assert(upgrade.includes('sessionStorage.setItem'),"Draft recovery should use session storage");
assert(!upgrade.includes('localStorage.setItem'),"Never persist captions across browser sessions");
assert(upgrade.includes('No post is automatically published'),"Publishing disclaimer must remain explicit");
assert(upgrade.includes('text/csv;charset=utf-8'),"Approved queue must offer portable CSV");
assert(upgrade.includes('^[\\s]*[=+@-]'),"CSV export must defend against spreadsheet formula injection");
assert(index.includes('studio-upgrades.css'),"New responsive upgrade CSS must be loaded");
assert(boot.includes('studio-upgrades.js'),"New upgrade module must be loaded");
assert(css.includes('@media(max-width:720px)'),"Mobile layout rules must be present");
assert(css.includes('prefers-reduced-motion'),"Reduced motion must be respected");
console.log("FOXON Studio static upgrade smoke checks passed.");
